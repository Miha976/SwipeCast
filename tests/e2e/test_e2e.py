import json, subprocess, time, sys
from playwright.sync_api import sync_playwright
hub = subprocess.Popen(['node', 'tests/e2e/hub-helper.mjs'], stdin=subprocess.PIPE, stdout=subprocess.PIPE, text=True, bufsize=1)
info = json.loads(hub.stdout.readline())
prev = subprocess.Popen(['npx', 'vite', 'preview', '--port', '4173', '--strictPort'], cwd='app', stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
time.sleep(2.5)
cmd = lambda c: (hub.stdin.write(c + '\n'), hub.stdin.flush())
ok = []
def check(n, c): ok.append(c); print(('PASS ' if c else 'FAIL ') + n)
try:
    with sync_playwright() as p:
        b = p.chromium.launch(executable_path='/usr/bin/google-chrome')
        ctx = b.new_context(viewport={'width': 390, 'height': 844}, device_scale_factor=2, is_mobile=True, has_touch=True)
        page = ctx.new_page()
        page.goto('http://localhost:4173/')
        page.get_by_text('Connecter ton PC').wait_for()
        page.screenshot(path='/tmp/sctest/ui-pairing-mobile.png')
        page.fill('#addr', f"127.0.0.1:{info['port']}")
        page.fill('#code', '000000'); page.get_by_role('button', name='Appairer').click()
        page.get_by_text('incorrect').wait_for(); check('mauvais code refusé avec message', True)
        page.fill('#code', info['code']); page.get_by_role('button', name='Appairer').click()
        page.get_by_text('PC-Bureau connecté').wait_for(timeout=8000); check('appairage + connexion WS', True)
        cmd('progress'); page.get_by_text('Reprendre ici').wait_for(timeout=5000)
        check('progression live du PC affichée', page.get_by_text('31:14').count() > 0)
        page.screenshot(path='/tmp/sctest/ui-home-mobile.png', full_page=True)
        cmd('handoff'); page.get_by_text('Regarder en plein écran').wait_for(timeout=5000)
        check('transfert entrant → feuille modale', True)
        time.sleep(4); page.screenshot(path='/tmp/sctest/ui-handoff-mobile.png')
        page.get_by_role('button', name='Plus tard').click(); time.sleep(0.5)
        cmd('dump'); acks = hub.stdout.readline()
        check('ack renvoyé au PC', 'handoff-ack' in acks)
        # reconnexion après rechargement (jeton persistant)
        page.reload(); page.get_by_text('PC-Bureau connecté').wait_for(timeout=8000); check('jeton persistant après rechargement', True)
        page.set_viewport_size({'width': 1280, 'height': 860})
        time.sleep(0.4); page.screenshot(path='/tmp/sctest/ui-home-desktop.png')
        b.close()
finally:
    hub.kill(); prev.kill()
print(f"{sum(ok)}/{len(ok)} OK"); sys.exit(0 if all(ok) else 1)
